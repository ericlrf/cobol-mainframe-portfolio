-- Exemplo didático de Native SQL Procedure para Db2 for z/OS.
CREATE PROCEDURE GET_ACCOUNT_LIMIT (
    IN  P_AGENCY  CHAR(4),
    IN  P_ACCOUNT CHAR(10),
    OUT P_LIMIT   DECIMAL(15,2),
    OUT P_STATUS  CHAR(1)
)
LANGUAGE SQL
READS SQL DATA
BEGIN
    SET P_LIMIT = NULL;
    SET P_STATUS = 'N';

    SELECT L.DAILY_LIMIT, A.STATUS_CODE
      INTO P_LIMIT, P_STATUS
      FROM ACCOUNT_LIMIT L
      JOIN CUSTOMER_ACCOUNT A
        ON A.AGENCY_CODE = L.AGENCY_CODE
       AND A.ACCOUNT_NO  = L.ACCOUNT_NO
     WHERE L.AGENCY_CODE = P_AGENCY
       AND L.ACCOUNT_NO  = P_ACCOUNT;
END;
