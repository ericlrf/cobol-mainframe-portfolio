CREATE TABLE CUSTOMER_ACCOUNT (
    AGENCY_CODE   CHAR(4)      NOT NULL,
    ACCOUNT_NO    CHAR(10)     NOT NULL,
    CUSTOMER_ID   CHAR(12)     NOT NULL,
    STATUS_CODE   CHAR(1)      NOT NULL,
    PRIMARY KEY (AGENCY_CODE, ACCOUNT_NO)
);

CREATE TABLE ACCOUNT_LIMIT (
    AGENCY_CODE   CHAR(4)       NOT NULL,
    ACCOUNT_NO    CHAR(10)      NOT NULL,
    DAILY_LIMIT   DECIMAL(15,2) NOT NULL,
    VERSION_NO    INTEGER       NOT NULL DEFAULT 1,
    UPDATED_AT    TIMESTAMP     NOT NULL,
    PRIMARY KEY (AGENCY_CODE, ACCOUNT_NO),
    FOREIGN KEY (AGENCY_CODE, ACCOUNT_NO)
      REFERENCES CUSTOMER_ACCOUNT (AGENCY_CODE, ACCOUNT_NO)
);

CREATE TABLE LIMIT_AUDIT (
    AUDIT_ID      BIGINT        NOT NULL,
    AGENCY_CODE   CHAR(4)       NOT NULL,
    ACCOUNT_NO    CHAR(10)      NOT NULL,
    OLD_LIMIT     DECIMAL(15,2) NOT NULL,
    NEW_LIMIT     DECIMAL(15,2) NOT NULL,
    EVENT_TS      TIMESTAMP     NOT NULL,
    CORRELATION_ID CHAR(36)     NOT NULL,
    PRIMARY KEY (AUDIT_ID)
);

CREATE TABLE BATCH_CHECKPOINT (
    JOB_NAME       VARCHAR(32) NOT NULL,
    BUSINESS_DATE  DATE        NOT NULL,
    LAST_KEY       VARCHAR(64),
    STATUS         VARCHAR(16) NOT NULL,
    UPDATED_AT     TIMESTAMP   NOT NULL,
    PRIMARY KEY (JOB_NAME, BUSINESS_DATE)
);

CREATE INDEX IX_LIMIT_UPDATED ON ACCOUNT_LIMIT (UPDATED_AT);
CREATE INDEX IX_AUDIT_ACCOUNT ON LIMIT_AUDIT (AGENCY_CODE, ACCOUNT_NO, EVENT_TS);
